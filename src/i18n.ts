export function suggestRemark(score: number | null, lang: Language): string {
  if (score === null || Number.isNaN(score)) return '';
  if (lang === 'fr') {
    if (score >= 18) return 'Excellent';
    if (score >= 16) return 'Très Bien';
    if (score >= 14) return 'Bien';
    if (score >= 12) return 'Assez Bien';
    if (score >= 10) return 'Passable';
    if (score >= 8) return 'Insuffisant';
    return 'Faible';
  }
  if (score >= 18) return 'Excellent';
  if (score >= 16) return 'Very Good';
  if (score >= 14) return 'Good';
  if (score >= 12) return 'Fair';
  if (score >= 10) return 'Average';
  if (score >= 8) return 'Weak';
  return 'Very Weak';
}

export function suggestCouncilAppreciation(average: number | null, lang: Language): string {
  if (average === null || Number.isNaN(average)) {
    return lang === 'fr' ? 'Résultats en attente de finalisation.' : 'Results pending completion.';
  }
  if (lang === 'fr') {
    if (average >= 16) return 'Excellent travail académique et conduite exemplaire. Félicitations du conseil.';
    if (average >= 14) return 'Très bon trimestre. Maintenir cette rigueur et cette régularité.';
    if (average >= 12) return 'Travail satisfaisant dans l’ensemble. Peut encore progresser avec plus d’efforts.';
    if (average >= 10) return 'Résultats passables. Un travail personnel plus soutenu est vivement conseillé.';
    return 'Résultats insuffisants. Doit redoubler d’efforts et bénéficier d’un suivi parental étroit.';
  }
  if (average >= 16) return 'Outstanding academic performance and exemplary conduct. Council commendation.';
  if (average >= 14) return 'Very good performance. Keep up the dedication and steady effort.';
  if (average >= 12) return 'Good overall standing. Capable of achieving even higher with continued focus.';
  if (average >= 10) return 'Average performance. More consistent personal study is encouraged.';
  return 'Below pass mark. Must double efforts with close parental supervision.';
}

export function formatRank(rank: number | null, total: number, lang: Language): string {
  if (!rank) return '—';
  if (lang === 'fr') {
    const suffix = rank === 1 ? 'er' : 'e';
    return `${rank}${suffix} / ${total}`;
  }
  const mod100 = rank % 100;
  let suffix = 'th';
  if (mod100 < 11 || mod100 > 13) {
    if (rank % 10 === 1) suffix = 'st';
    else if (rank % 10 === 2) suffix = 'nd';
    else if (rank % 10 === 3) suffix = 'rd';
  }
  return `${rank}${suffix} / ${total}`;
}
